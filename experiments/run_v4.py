"""
v4 experiment: how should rules and similarity be blended when we do not know
which definition of 'taste' is right?

The large catalog has no real listening data, so two synthetic protocols stand in
for two opposite assumptions about what a listener likes:
  * genre-taste: they like whole genres        -> favours label-based rules
  * audio-taste: they like things that sound like their seeds -> favours similarity
For each blend weight we compute NDCG@5 under both. Selection rule (declared
before looking at results): pick the blend with the best WORST-case score,
ties to the smaller similarity weight.

Usage:  python -m experiments.run_v4
"""
import statistics
from pathlib import Path

from experiments.datasets import load_dataset
from experiments.run_v1 import K, patched, score
from experiments.run_v3 import RULE_PARTS, ndcg
from src import recommender as rec
from src.baselines import centroid_knn
from src.metrics import cluster_bootstrap_ci

ROOT = Path(__file__).resolve().parent.parent
WEIGHTS = [1, 3, 8, 20]   # v3 stopped at 3; extended after seeing that 3 was not enough
MODES = ["centroid", "nearest"]
PROTOCOLS = {"large": "Genre taste", "large_audio": "Audio taste"}


def sweep(dataset):
    songs, listeners = load_dataset(dataset)
    groups = [l["group"] for l in listeners]
    rows = {"Rules only": [ndcg(l, songs, "centroid", 0.0) for l in listeners]}
    for retrieval in (True, False):
        tag = "" if retrieval else ", no retrieval filter"
        for mode in MODES:
            for w in WEIGHTS:
                rows[f"Rules + {mode} similarity (weight {w:g}){tag}"] = [
                    ndcg(l, songs, mode, float(w), retrieval=retrieval) for l in listeners]
    for mode in MODES:
        rows[f"Similarity only ({mode})"] = [ndcg(l, songs, mode, 1.0, rules=False) for l in listeners]
    from experiments.run_v1 import K as _k
    rows["Audio-feature nearest neighbours (v1 baseline)"] = [
        score(centroid_knn(l["seeds"], l["catalog"], _k), l["relevant"])["ndcg"] for l in listeners]
    return rows, groups


def run():
    out = {}
    for dataset in PROTOCOLS:
        out[dataset] = sweep(dataset)
    return out


def build_report(res):
    names = list(res["large"][0])
    mean = {d: {n: statistics.mean(res[d][0][n]) for n in names} for d in PROTOCOLS}
    ci = {d: {n: cluster_bootstrap_ci(res[d][0][n], res[d][1]) for n in names} for d in PROTOCOLS}

    blends = [n for n in names if n.startswith("Rules")]
    worst = {n: min(mean[d][n] for d in PROTOCOLS) for n in blends}
    avg = {n: statistics.mean(mean[d][n] for d in PROTOCOLS) for n in blends}
    best = max(blends, key=lambda n: (round(worst[n], 6), -blends.index(n)))
    shipped = f"Rules + {rec.SIMILARITY_MODE} similarity (weight {rec.WEIGHTS['similarity']:g}), no retrieval filter"

    L = []
    w = L.append
    w(f"# v4 results: blending rules and similarity on the large catalog (k={K}, 1985 songs, 60 listeners in 10 archetypes)\n")
    w("Generated by `python -m experiments.run_v4`. There is no real listening data, so two synthetic protocols stand in for two "
      "opposite ideas of taste: **genre taste** (a listener likes whole genres, which favours label-based rules) and **audio "
      "taste** (a listener likes songs that sound like their seeds in a richer feature space the recommender cannot fully see, "
      "which favours similarity). Metric: NDCG@5. Intervals resample whole archetypes.\n")
    w("## Trade-off table\n")
    w("| Method | Genre taste | Audio taste | Worst case | Average |")
    w("|---|---|---|---|---|")
    for n in names:
        g, a = mean["large"][n], mean["large_audio"][n]
        mark = (" **(declared rule)**" if n == best else "") + (" **(shipped default)**" if n == shipped else "")
        wc = f"{min(g, a):.3f}"
        av = f"{(g + a) / 2:.3f}"
        w(f"| {n}{mark} | {g:.3f} ({ci['large'][n][0]:.2f} to {ci['large'][n][1]:.2f}) | "
          f"{a:.3f} ({ci['large_audio'][n][0]:.2f} to {ci['large_audio'][n][1]:.2f}) | {wc} | {av} |")
    w("")
    w(f"**Declared rule:** best worst-case score across the two protocols, ties to the smaller weight. It selects **{best}** "
      f"(genre taste {mean['large'][best]:.3f}, audio taste {mean['large_audio'][best]:.3f}).\n")
    if shipped in mean["large"] and shipped != best:
        g0, a0 = mean["large"]["Rules only"], mean["large_audio"]["Rules only"]
        g1, a1 = mean["large"][shipped], mean["large_audio"][shipped]
        w(f"**Shipped default:** {shipped}. That rule's pick gives up {g0 - mean['large'][best]:.2f} NDCG under genre taste to "
          f"gain {mean['large_audio'][best] - a0:.2f} under audio taste. The shipped default is a judgement call at the knee of "
          f"the curve instead: {g1 - g0:+.2f} under genre taste for {a1 - a0:+.2f} under audio taste, relative to rules only. "
          "Change `WEIGHTS[\"similarity\"]` in `src/recommender.py` to move along the trade-off.\n")
    w("## How to read this\n")
    w("- No single method wins both protocols: the rules are near-perfect when taste is genre-defined and weak when it is sound-defined, and similarity does the opposite.")
    w("- Blending trades one for the other. The right weight depends on how real listeners behave, which this dataset cannot tell us.")
    w("- These are synthetic benchmarks. They show how the system behaves under two clearly stated assumptions, not how good the recommendations are for real people.")
    return "\n".join(L) + "\n", best, mean


def main():
    res = run()
    report, best, mean = build_report(res)
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports/v4_results.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
