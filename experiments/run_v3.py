"""
v3 experiment: does blending in similarity to the user's liked songs improve the rules?

Candidates (declared before looking at results):
  * rules only (the system as of v2)
  * rules + similarity to the AVERAGE sound of the liked songs ("centroid")
  * rules + similarity to the CLOSEST single liked song ("nearest")
each at several blend weights. The choice is validated leave-one-listener-out.

Usage:  python -m experiments.run_v3
"""
import argparse
import statistics
from pathlib import Path

from experiments.datasets import DATASETS, load_dataset
from experiments.run_v1 import K, patched, score
from src import recommender as rec
from src.metrics import cluster_bootstrap_ci
from src.recommender import recommend_songs
from src.tuning import leave_one_out_simplest

ROOT = Path(__file__).resolve().parent.parent
WEIGHTS_TO_TRY = [0.5, 1.0, 2.0, 3.0]
MODES = ["centroid", "nearest"]
RULE_PARTS = {"genre": 0.0, "mood": 0.0, "energy": 0.0, "acoustic": 0.0}


def ndcg(listener, songs, mode, weight, rules=True, retrieval=None):
    """NDCG@5 for one listener. retrieval=None keeps the genre/mood filter on whenever the rules are on."""
    prefs = dict(listener["profile"])
    weights = {"similarity": weight}
    # Always pass the seeds as liked songs so they are excluded from results,
    # even when the similarity weight is 0 (rules only). This keeps every
    # candidate on the same footing as v1.
    prefs["liked_ids"] = [s["id"] for s in listener["seeds"]]
    if not rules:
        weights.update(RULE_PARTS)
    saved = rec.SIMILARITY_MODE
    rec.SIMILARITY_MODE = mode
    try:
        # filter_when_liked=True makes the genre/mood filter apply even with liked songs, so the
        # no_retrieval switch below fully controls the experiment (product default is no filter).
        with patched(weights=weights, filter_when_liked=True,
                     no_retrieval=(not rules) if retrieval is None else (not retrieval)):
            ids = [s["id"] for s, _, _ in recommend_songs(prefs, songs, k=K)]
    finally:
        rec.SIMILARITY_MODE = saved
    return score(ids, listener["relevant"])["ndcg"]


def run(dataset="small"):
    songs, listeners = load_dataset(dataset)
    configs = [("rules only", None, 0.0)]
    configs += [(f"rules + {m} similarity, weight {w:g}", m, w) for m in MODES for w in WEIGHTS_TO_TRY]
    matrix = [[ndcg(l, songs, m or "centroid", w) for l in listeners] for _, m, w in configs]
    complexity = [0.0] + [WEIGHTS_TO_TRY.index(w) + 1 + (len(WEIGHTS_TO_TRY) if m == "nearest" else 0)
                          for _, m, w in configs[1:]]
    groups = [l["group"] for l in listeners]
    folds = leave_one_out_simplest(matrix, complexity, groups=groups)
    similarity_only = {m: [ndcg(l, songs, m, 1.0, rules=False) for l in listeners] for m in MODES}
    return listeners, configs, matrix, folds, similarity_only, dataset


def build_report(listeners, configs, matrix, folds, similarity_only, dataset="small"):
    groups = [l["group"] for l in listeners]
    names = list(dict.fromkeys(groups))
    many = len(listeners) > 12

    def by_group(row):
        acc = {}
        for v, g in zip(row, groups):
            acc.setdefault(g, []).append(v)
        return [statistics.mean(acc[g]) for g in names]

    protocol = {"small": "7 hand-labelled listeners",
                "large": "genre-taste protocol (taste defined by genre: favours label-based methods)",
                "large_audio": "audio-taste protocol (taste defined by sound in a richer feature space: favours similarity)"}[dataset]
    out = []
    w = out.append
    w(f"# v3 results ({dataset} catalog): similarity to liked songs (k={K}, {len(listeners)} listeners in {len(names)} groups)\n")
    w(f"Generated by `python -m experiments.run_v3 --dataset {dataset}`. Protocol: {protocol}. The listener's "
      "3 seed songs play the role of 'songs I already like'; they are never recommended back. Metric: NDCG@5. "
      "Intervals resample whole groups.\n")

    w("## 1. Each candidate, averaged over all listeners\n")
    w("| Candidate | Mean NDCG@5 | " + " | ".join(names) + " |")
    w("|---|---|" + "---|" * len(names))
    for (name, _, _), row in zip(configs, matrix):
        w(f"| {name} | {statistics.mean(row):.3f} | " + " | ".join(f"{v:.2f}" for v in by_group(row)) + " |")
    for m in MODES:
        row = similarity_only[m]
        w(f"| similarity only ({m}), no rules | {statistics.mean(row):.3f} | " + " | ".join(f"{v:.2f}" for v in by_group(row)) + " |")

    w("\n## 2. Honest check: hold out one group at a time\n")
    w("Pick the best candidate on the other groups (ties go to the simplest), then score it on the held-out one.\n")
    w("| Held-out group | Candidate chosen on the rest | Chosen | Rules only | Difference |")
    w("|---|---|---|---|---|")
    for f, g in zip(folds, names):
        w(f"| {g} | {configs[f['config_index']][0]} | {f['chosen']:.2f} | {f['baseline']:.2f} | {f['chosen'] - f['baseline']:+.2f} |")
    chosen = statistics.mean(f["chosen"] for f in folds)
    base = statistics.mean(f["baseline"] for f in folds)
    lo, hi = cluster_bootstrap_ci([f["chosen"] - f["baseline"] for f in folds], list(range(len(folds))))
    w(f"| **Mean** | | **{chosen:.3f}** | **{base:.3f}** | **{chosen - base:+.3f}** (95% interval {lo:+.2f} to {hi:+.2f}) |\n")
    best = max(range(len(configs)), key=lambda c: statistics.mean(matrix[c]))
    w(f"Best candidate on all listeners: **{configs[best][0]}** ({statistics.mean(matrix[best]):.3f} "
      f"vs {statistics.mean(matrix[0]):.3f} for rules only).\n")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", choices=list(DATASETS), default="small")
    args = ap.parse_args()
    report = build_report(*run(args.dataset))
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / f"reports/v3_results{DATASETS[args.dataset]['suffix']}.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
